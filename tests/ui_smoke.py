"""Optional real-browser smoke checks. Start server.py before running."""
import os
from playwright.sync_api import sync_playwright, expect
BASE=os.environ.get('TEST_BASE_URL','http://127.0.0.1:3000')
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path=os.environ.get('BROWSER_PATH','/usr/bin/chromium'),args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1100})
    errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto(BASE,wait_until='networkidle')
    expect(page.locator('#data-notice')).to_contain_text('Demo çalışma alanı')
    old=page.locator('#views').inner_text()
    page.locator('#period').select_option('7')
    assert old!=page.locator('#views').inner_text()
    page.locator('[data-format="short"]').click()
    assert page.locator('#featured .video-card').count()==1
    page.locator('[data-format="all"]').click()
    page.locator('#period').select_option('28')
    page.locator('#featured .video-card').first.click()
    expect(page.locator('#video-dialog')).to_be_visible()
    page.keyboard.press('Escape')
    page.locator('[data-page="videos"]').click()
    page.locator('#search').fill('Böyle bir video yok')
    expect(page.locator('#video-empty')).to_be_visible()
    page.locator('#search').fill('Sıfırdan')
    assert page.locator('#video-rows tr').count()==1
    page.locator('#search').fill('')
    page.locator('#sort').select_option('hours')
    page.locator('[data-page="insights"]').click()
    page.locator('#all-insights button').first.click()
    expect(page.locator('#plan-dialog')).to_be_visible()
    page.locator('#plan-form input').fill('Açılış denemesi')
    page.locator('#plan-form button[type="submit"]').click()
    expect(page.locator('#view-plan')).to_be_visible()
    expect(page.locator('#plan-idea')).to_contain_text('Açılış denemesi')
    page.locator('#plan-idea select').select_option('progress')
    expect(page.locator('#plan-progress')).to_contain_text('Açılış denemesi')
    page.reload(wait_until='networkidle')
    expect(page.locator('#plan-progress')).to_contain_text('Açılış denemesi')
    page.locator('#plan-progress button').click()
    expect(page.locator('#count-progress')).to_have_text('0')
    page.locator('[data-page="settings"]').click()
    page.locator('#settings-connect').click()
    expect(page.locator('#connect-dialog')).to_be_visible()
    expect(page.locator('#oauth-start')).to_be_disabled()
    page.keyboard.press('Escape')
    csv='Video title,Views,Watch time (hours),Subscribers\n"<img src=x onerror=alert(1)>",120,3,2\nOther,80,1,-1'
    page.locator('#csv').set_input_files({'name':'studio.csv','mimeType':'text/csv','buffer':csv.encode()})
    expect(page.locator('#views')).to_have_text('200')
    expect(page.locator('#fourth')).to_have_text('—')
    expect(page.locator('#period')).to_be_disabled()
    assert page.locator('#video-rows img[src="x"]').count()==0
    assert page.locator('#chart .csv-bar-row').count()==2
    page.evaluate("location.hash='settings'")
    page.locator('#csv').set_input_files({'name':'bad.csv','mimeType':'text/csv','buffer':b'Wrong,Data\na,b'})
    expect(page.locator('#message')).to_contain_text('sütunları gerekli')
    expect(page.locator('#views')).to_have_text('200')
    page.locator('#demo').click()
    expect(page.locator('#data-notice')).to_contain_text('Demo çalışma alanı')
    page.screenshot(path='/tmp/creator-desktop.png',full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    # Mobile navigation and dialogs, with no horizontal overflow.
    mobile=browser.new_page(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
    mobile.on('pageerror',lambda error:errors.append(str(error)))
    mobile.goto(BASE,wait_until='networkidle')
    assert mobile.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    mobile.screenshot(path='/tmp/creator-mobile.png',full_page=True)
    mobile.locator('#mobile-menu').click()
    mobile.locator('[data-page="plan"]').click()
    expect(mobile.locator('#view-plan')).to_be_visible()
    mobile.locator('#new-plan').click()
    expect(mobile.locator('#plan-dialog')).to_be_visible()
    mobile.locator('#plan-form input').fill('Mobil fikir')
    mobile.locator('#plan-form button[type="submit"]').click()
    expect(mobile.locator('#plan-idea')).to_contain_text('Mobil fikir')
    # Connected UI exercised with explicit mocked provider output, never real metrics.
    live=browser.new_page(viewport={'width':1280,'height':900})
    live.on('pageerror',lambda error:errors.append(str(error)))
    live.route('**/api/status',lambda route:route.fulfill(json={'configured':True,'connected':True,'channel':{'title':'Eren','handle':'@erenbyndir'}}))
    requested=[]
    def report(route):
        requested.append(route.request.url)
        route.fulfill(json={'start':'2026-09-12','end':'2026-10-09','summary':{'views':123,'hours':2,'subscribers':-2,'avgSeconds':60},'videos':[{'id':'abcdefghijk','title':'Mock live video','views':123,'hours':2,'subscribers':-2,'avgSeconds':60,'impressions':None,'ctr':None}],'daily':[{'date':'2026-10-09','views':123}]})
    live.route('**/api/analytics?*',report)
    live.goto(BASE,wait_until='networkidle')
    expect(live.locator('#data-notice')).to_contain_text('YouTube Analytics bağlı')
    expect(live.locator('#views')).to_have_text('123')
    expect(live.locator('#subscribers')).to_have_text('-2')
    expect(live.locator('[data-format="short"]')).to_be_disabled()
    live.locator('#period').select_option('7')
    live.wait_for_function("document.getElementById('refresh').disabled === false")
    assert any('days=7' in url for url in requested)
    live.route('**/api/analytics?*',lambda route:route.fulfill(status=502,json={'error':'Google erişimi reddetti.'}))
    live.locator('#refresh').click()
    expect(live.locator('#message')).to_contain_text('Google erişimi reddetti')
    expect(live.locator('#views')).to_have_text('123')
    assert errors==[],errors
    print('Browser checks passed: filters, video detail, search/sort, plan persistence, OAuth state, CSV/error/XSS, mobile navigation, live reporting and API failure.')
    browser.close()
